import { existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = join(dirname(fileURLToPath(import.meta.url)), "..");
const coreRoot = join(repoRoot, "packages/core");

const GLOBAL_ATTRS = ["id", "lang", "dir", "data-step", "aria-*", "role"];
const RUNTIME_URL = /https:\/\/cdn\.jsdelivr\.net\/npm\/(?:@bangerpage\/core|banger-core)@[^/\s"']+\/dist\/(index|standalone)\.js/g;

/** `'a' | 'b' | undefined` -> `["a", "b"]`; null when the type is not a union of string literals. */
export function parseUnion(text) {
  const parts = text
    .split("|")
    .map((part) => part.trim())
    .filter((part) => part !== "undefined");
  if (parts.length === 0) return null;
  const values = [];
  for (const part of parts) {
    const match = /^(?:"([^"]*)"|'([^']*)')$/.exec(part);
    if (!match) return null;
    values.push(match[1] ?? match[2]);
  }
  return values;
}

function valuesOf(typeText, description) {
  const union = parseUnion(typeText);
  if (union) return union.map((v) => `\`${v}\``).join(", ");
  const plain = typeText
    .split("|")
    .map((part) => part.trim())
    .filter((part) => part !== "undefined")
    .join(" | ");
  const type = plain === "" ? "string" : plain;
  return /^Required\./.test(description) && type === "string" ? "string, required" : type;
}

const cell = (text) => text.replace(/\s*\n\s*/g, " ").replace(/\|/g, "\\|").trim();

function unquote(value) {
  if (value === undefined) return "";
  const match = /^(?:"([^"]*)"|'([^']*)')$/.exec(value);
  return match ? (match[1] ?? match[2]) : value;
}

function attributeRows(decl) {
  const members = decl.members ?? [];
  return (decl.attributes ?? []).map((attr) => {
    const member = members.find((m) => m.kind === "field" && m.attribute === attr.name);
    const description = cell(member?.description ?? attr.description ?? "");
    const typeText = member?.type?.text ?? attr.type?.text ?? "string";
    const def = unquote(member?.default ?? attr.default);
    return `| \`${attr.name}\` | ${cell(valuesOf(typeText, description))} | ${def === "" ? "-" : `\`${cell(def)}\``} | ${description} |`;
  });
}

/** Markdown for `skill/reference/components.md`, from a parsed `custom-elements.json`. */
export function renderComponentsMd(manifest) {
  const decls = manifest.modules
    .flatMap((module) => module.declarations ?? [])
    .filter((decl) => decl.kind === "class" && decl.tagName)
    .sort((a, b) => (a.tagName < b.tagName ? -1 : a.tagName > b.tagName ? 1 : 0));
  const lines = [
    "<!-- Generated by scripts/gen-skill.mjs from custom-elements.json. Do not edit by hand. -->",
    "",
    "# Components",
    "",
    `Every element accepts these global attributes: ${GLOBAL_ATTRS.map((a) => `\`${a}\``).join(" ")}. Never write a \`style\` attribute except inside \`bang-free\`; pick values from the attributes below instead.`,
    "",
  ];
  for (const decl of decls) {
    lines.push(`## ${decl.tagName}`, "");
    if (decl.description) lines.push(decl.description.trim(), "");
    const rows = attributeRows(decl);
    if (rows.length === 0) lines.push("No attributes.", "");
    else {
      lines.push("| Attribute | Values | Default | Description |", "| --- | --- | --- | --- |", ...rows, "");
    }
    const slots = decl.slots ?? [];
    if (slots.length > 0) {
      lines.push(
        "Slots:",
        "",
        ...slots.map((slot) => `- ${slot.name ? `\`${slot.name}\`` : "default"}: ${cell(slot.description ?? "")}`),
        "",
      );
    }
  }
  return `${lines.join("\n").trimEnd()}\n`;
}

/** Rewrites the runtime URL's `<name>@<version>` to match the core package. Returns the new text. */
export function stampText(text, name, version) {
  return text.replace(RUNTIME_URL, (_url, file) => `https://cdn.jsdelivr.net/npm/${name}@${version}/dist/${file}.js`);
}

function filesToStamp() {
  const fixtures = join(repoRoot, "packages/cli/test/fixtures");
  const list = [
    join(repoRoot, "skill/templates/starter.html"),
    join(repoRoot, "examples/minimal/index.html"),
    join(repoRoot, "examples/showcase/index.html"),
    join(repoRoot, "README.md"),
    join(repoRoot, "README.ja.md"),
    join(repoRoot, "packages/core/README.md"),
  ];
  if (existsSync(fixtures)) {
    for (const name of readdirSync(fixtures).sort()) if (name.endsWith(".html")) list.push(join(fixtures, name));
  }
  return list.filter((file) => existsSync(file));
}

/** Updates the runtime URL in the starter, the example and the CLI fixtures. Idempotent. */
export function stampRuntimeUrls() {
  const { name, version } = JSON.parse(readFileSync(join(coreRoot, "package.json"), "utf8"));
  const changed = [];
  for (const file of filesToStamp()) {
    const before = readFileSync(file, "utf8");
    const after = stampText(before, name, version);
    if (after !== before) {
      writeFileSync(file, after);
      changed.push(file);
    }
  }
  return changed;
}

/** Sets the Claude Code plugin's version to the CLI's, so installed plugins update when a release ships. */
export function stampPluginVersion() {
  const file = join(repoRoot, ".claude-plugin/plugin.json");
  const { version } = JSON.parse(readFileSync(join(repoRoot, "packages/cli/package.json"), "utf8"));
  const before = readFileSync(file, "utf8");
  const after = `${JSON.stringify({ ...JSON.parse(before), version }, null, 2)}\n`;
  if (after !== before) writeFileSync(file, after);
}

function write(file, text) {
  mkdirSync(dirname(file), { recursive: true });
  writeFileSync(file, text);
}

function main(argv) {
  const index = argv.indexOf("--out-dir");
  const outDir = index >= 0 ? argv[index + 1] : undefined;
  if (index >= 0 && !outDir) throw new Error("--out-dir needs a directory");
  const manifest = JSON.parse(readFileSync(join(coreRoot, "custom-elements.json"), "utf8"));
  const components = renderComponentsMd(manifest);
  if (outDir) {
    const { name, version } = JSON.parse(readFileSync(join(coreRoot, "package.json"), "utf8"));
    write(join(outDir, "reference/components.md"), components);
    const starter = readFileSync(join(repoRoot, "skill/templates/starter.html"), "utf8");
    write(join(outDir, "templates/starter.html"), stampText(starter, name, version));
    return;
  }
  write(join(repoRoot, "skill/reference/components.md"), components);
  stampRuntimeUrls();
  stampPluginVersion();
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) main(process.argv.slice(2));
