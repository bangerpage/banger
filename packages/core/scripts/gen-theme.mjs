import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const TOKENS_PATH = join(here, "..", "tokens.json");
const OUT_PATH = join(here, "..", "src/theme/theme.generated.ts");

export const EXCLUDED_COLOR_TOKENS = ["lime", "on-lime"];
export const PRESENTATION_SIZES = { xs: 28, s: 36, m: 48, l: 64, xl: 96, "2xl": 144 };
export const PRESENTATION_LEADING = { xs: 1.6, s: 1.5, m: 1.35, l: 1.1, xl: 1.0, "2xl": 0.95 };
export const PRESENTATION_GAPS = {
  xs: "space-4",
  s: "space-6",
  m: "space-8",
  l: "space-12",
  xl: "space-16",
  "2xl": "space-24",
};
export const FRAME_GAP = 240;

function resolveColor(value, theme, byName) {
  const match = /^\{([^}]+)\}$/.exec(value);
  if (!match) return value;
  const ref = byName.get(match[1]);
  if (!ref) throw new Error(`gen-theme: color token "${match[1]}" referenced by a reference is missing`);
  return resolveColor(ref.value[theme], theme, byName);
}

function requireToken(tokens, name, group) {
  if (!tokens.some((t) => t.name === name)) {
    throw new Error(`gen-theme: token "${name}" is missing from tokens.json (${group})`);
  }
}

/**
 * @param {any} tokens parsed packages/core/tokens.json
 * @param {{ gaps?: Record<string, string> }} [opts]
 */
export function buildThemeCss(tokens, opts = {}) {
  const gaps = opts.gaps ?? PRESENTATION_GAPS;
  const colors = tokens.color.tokens;
  const byName = new Map(colors.map((t) => [t.name, t]));
  const included = colors.filter((t) => !EXCLUDED_COLOR_TOKENS.includes(t.name));
  const spacing = tokens.spacing.tokens;
  for (const token of Object.values(gaps)) requireToken(spacing, token, "spacing");

  const colorLines = (theme) =>
    included.map((t) => `  --bang-color-${t.name}: ${resolveColor(t.value[theme], theme, byName)};`);
  const strip = (name, prefix) => name.slice(prefix.length);
  const lines = (list, prefix, cssPrefix) =>
    list.map((t) => `  --bang-${cssPrefix}-${strip(t.name, prefix)}: ${t.value};`);

  const root = [
    ...colorLines("light"),
    ...["display", "sans", "mono"].map((k) => {
      if (!tokens.type.families[k]) throw new Error(`gen-theme: type.families.${k} is missing`);
      return `  --bang-font-${k}: ${tokens.type.families[k]};`;
    }),
    ...lines(spacing, "space-", "space"),
    ...lines(tokens.radius.tokens, "radius-", "radius"),
    ...lines(tokens.borderWidth.tokens, "border-", "border"),
    ...Object.entries(PRESENTATION_SIZES).map(([k, v]) => `  --bang-size-${k}: ${v}px;`),
    ...Object.entries(PRESENTATION_LEADING).map(([k, v]) => `  --bang-leading-${k}: ${v};`),
    ...Object.keys(PRESENTATION_SIZES).map((k) => {
      if (!gaps[k]) throw new Error(`gen-theme: no gap token for size "${k}"`);
      return `  --bang-gap-${k}: var(--bang-${gaps[k]});`;
    }),
    "  --bang-tone-default: var(--bang-color-ink);",
    "  --bang-tone-muted: var(--bang-color-ink-muted);",
    "  --bang-tone-accent: var(--bang-color-signal-text);",
    `  --bang-frame-gap: ${FRAME_GAP}px;`,
    "  --bang-duration-fast: 200ms;",
  ];

  return [
    ":host {",
    ...root,
    "}",
    ':host([theme="dark"]) {',
    ...colorLines("dark"),
    "}",
    "",
  ].join("\n");
}

/** The ten color tokens of each theme with references resolved, in tokens.json order. */
export function buildThemeColorTokens(tokens) {
  const colors = tokens.color.tokens;
  const byName = new Map(colors.map((t) => [t.name, t]));
  const included = colors.filter((t) => !EXCLUDED_COLOR_TOKENS.includes(t.name));
  const pickTheme = (theme) =>
    Object.fromEntries(included.map((t) => [t.name, resolveColor(t.value[theme], theme, byName)]));
  return { light: pickTheme("light"), dark: pickTheme("dark") };
}

export function buildThemeFontStacks(tokens) {
  const families = {};
  for (const k of ["display", "sans", "mono"]) {
    if (!tokens.type.families[k]) throw new Error(`gen-theme: type.families.${k} is missing`);
    families[k] = tokens.type.families[k];
  }
  return families;
}

export const FONTS_HREF =
  "https://fonts.googleapis.com/css2?family=Bricolage+Grotesque:opsz,wght@12..96,800&family=Noto+Sans+JP:wght@400;700&family=JetBrains+Mono:wght@400&display=swap";

function escapeTemplate(text) {
  return text.replace(/\\/g, "\\\\").replace(/`/g, "\\`").replace(/\$\{/g, "\\${");
}

export function buildThemeModule(tokens, href = FONTS_HREF) {
  const css = buildThemeCss(tokens);
  return [
    "// Generated by scripts/gen-theme.mjs from packages/core/tokens.json. Do not edit.",
    `export const themeCss = \`${escapeTemplate(css)}\`;`,
    `export const fontsHref = ${JSON.stringify(href)};`,
    `export const themeColorTokens = ${JSON.stringify(buildThemeColorTokens(tokens), null, 2)} as const;`,
    `export const themeFontStacks = ${JSON.stringify(buildThemeFontStacks(tokens), null, 2)} as const;`,
    "",
  ].join("\n");
}

if (process.argv[1] && fileURLToPath(import.meta.url) === process.argv[1]) {
  const tokens = JSON.parse(readFileSync(TOKENS_PATH, "utf8"));
  writeFileSync(OUT_PATH, buildThemeModule(tokens));
}
